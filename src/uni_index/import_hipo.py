"""
Importer for the Hipo university-domains-list dataset
(https://github.com/Hipo/university-domains-list).

Writes one generated YAML file per country into data/sources/imported/, plus a report of
every entry it skipped and why. Generated files are never hand-edited: to change an imported
entry, override it in data/sources/curated/ instead (see README).

Usage:
    uni-index import-hipo world_universities.json
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Dict, List, Optional

from .io_utils import write_by_country
from .models import ValidationErrorList, build_canonical_university

IMPORTED_HEADER = (
    "# GENERATED by `uni-index import-hipo` from {source} (sha256 {digest}).\n"
    "# Do not edit by hand - re-running the importer overwrites this file.\n"
    "# To change an entry, override it in data/sources/curated/ instead.\n"
)


def convert_entry(entry: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """
    Convert one raw Hipo dataset entry into our source-file schema.
    Returns None if the entry can't be converted (missing domain or country).
    """
    domains = entry.get("domains") or []
    if not domains:
        return None

    domain = str(domains[0]).strip().lower()
    if not domain:
        return None

    country = str(entry.get("alpha_two_code") or "").strip().upper()
    if not country:
        return None

    return {
        "domain": domain,
        "country": country,
        "type": "other",       # Hipo doesn't classify public/private - refine in curated/
        "priority": 3,         # default priority - refine in curated/ for schools you prioritize
        "subdomains": [],      # Hipo doesn't include these - Phase 2 (crt.sh) fills them in
    }


def import_hipo(json_path: Path, out_dir: Path, report_path: Path) -> Dict[str, int]:
    """
    Validate every Hipo entry with the same validator `normalize` uses, write the accepted
    ones to out_dir/<country>.yaml, and quarantine the rest in report_path.
    Deterministic: unchanged input -> byte-identical output.
    """
    raw_bytes = json_path.read_bytes()
    digest = hashlib.sha256(raw_bytes).hexdigest()
    raw_entries = json.loads(raw_bytes.decode("utf-8"))
    if not isinstance(raw_entries, list):
        raise ValueError("expected a JSON array of universities")

    accepted: List[Dict[str, Any]] = []
    rejected: List[Dict[str, Any]] = []
    duplicates: List[Dict[str, Any]] = []
    kept_name_by_domain: Dict[str, str] = {}

    for entry in raw_entries:
        if not isinstance(entry, dict):
            rejected.append({"name": "?", "problems": ["entry is not an object"], "raw": entry})
            continue
        name = str(entry.get("name") or "?")
        record = convert_entry(entry)
        if record is None:
            rejected.append({"name": name, "problems": ["no usable domain or country code"], "raw": entry})
            continue
        try:
            build_canonical_university(record)
        except ValidationErrorList as e:
            rejected.append({"name": name, "problems": e.problems, "raw": entry})
            continue
        domain = record["domain"]
        if domain in kept_name_by_domain:
            duplicates.append({"name": name, "domain": domain, "kept": kept_name_by_domain[domain]})
            continue
        kept_name_by_domain[domain] = name
        accepted.append(record)

    # out_dir holds generated files only, so stale country files are cleared before writing
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("*.yaml"):
        stale.unlink()
    per_country = write_by_country(accepted, out_dir, IMPORTED_HEADER.format(source=json_path.name, digest=digest))

    stats = {
        "total": len(raw_entries),
        "accepted": len(accepted),
        "rejected": len(rejected),
        "duplicates": len(duplicates),
        "countries": len(per_country),
    }
    report = {"source": json_path.name, "sha256": digest, "counts": stats,
              "rejected": rejected, "duplicates": duplicates}
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(
        "# GENERATED by `uni-index import-hipo` - what the importer skipped, and why.\n"
        # JSON is a YAML 1.2 subset, keeping reports readable without PyYAML.
        + json.dumps(report, indent=2, ensure_ascii=False)
        + "\n",
        encoding="utf-8",
    )
    return stats


if __name__ == "__main__":
    # the old `python -m uni_index.import_hipo in.json out.yaml` entry point: fail loudly, not silently
    raise SystemExit("This entry point moved: run `uni-index import-hipo <file.json>` instead.")
